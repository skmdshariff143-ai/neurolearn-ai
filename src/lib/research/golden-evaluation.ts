export interface BenchmarkValidationResult {
  topicId: string;
  topic: string;
  passed: boolean;
  classifiedSubject: string;
  expectedSubject: string;
  prerequisites: string[];
  sourcesRetrieved: number;
  sourcesVerified: boolean;
  termMatchRate: number;
  notes: string[];
}

export async function evaluateBenchmarkTopic(
  benchmark: GoldenBenchmarkTopic,
  coordinator: UniversalResearchCoordinator,
): Promise<BenchmarkValidationResult> {
  const notes: string[] = [];
  const plan = buildResearchPlan(benchmark.topic, benchmark.recommendedLevel, "English");

  const classifiedSubject = plan.subject;
  const subjectMatched =
    classifiedSubject.toLowerCase().includes(benchmark.expectedSubject.toLowerCase()) ||
    benchmark.expectedSubject.toLowerCase().includes(classifiedSubject.toLowerCase());

  if (!subjectMatched) {
    notes.push(`Subject mismatch: got ${classifiedSubject}, expected ${benchmark.expectedSubject}`);
  }

  const hasPrereqs = plan.prerequisites.length >= 2;
  if (!hasPrereqs) {
    notes.push(`Too few prerequisites: ${plan.prerequisites.length}`);
  }

  const researchResult = await coordinator.coordinateResearch(benchmark.topic, benchmark.recommendedLevel, "English", 4);

  const sourcesRetrieved = researchResult.sources.length;
  const sourcesVerified = researchResult.sources.length > 0 &&
    researchResult.sources.every((s) => s.url.startsWith("https://") && s.title.length > 3);

  if (!sourcesVerified) {
    notes.push(`Source verification issue: retrieved ${sourcesRetrieved}`);
  }

  // Check essential term coverage in source excerpts + titles
  const allSourceText = researchResult.sources
    .map((s) => `${s.title} ${s.excerpt}`.toLowerCase())
    .join(" ");

  let matchedTerms = 0;
  for (const term of benchmark.essentialTerms) {
    if (allSourceText.includes(term.toLowerCase())) {
      matchedTerms++;
    }
  }

  const termMatchRate = benchmark.essentialTerms.length > 0
    ? matchedTerms / benchmark.essentialTerms.length
    : 1;

  if (termMatchRate < 0.2) {
    notes.push(`Low term match rate: ${(termMatchRate * 100).toFixed(0)}%`);
  }

  const passed = sourcesRetrieved > 0 && sourcesVerified;

  return {
    topicId: benchmark.id,
    topic: benchmark.topic,
    passed,
    classifiedSubject,
    expectedSubject: benchmark.expectedSubject,
    prerequisites: plan.prerequisites,
    sourcesRetrieved,
    sourcesVerified,
    termMatchRate,
    notes,
  };
}
